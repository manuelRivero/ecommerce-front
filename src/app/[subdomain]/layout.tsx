export default async function RootLayout({
  children,
  params,
}: {
  children: React.ReactNode;
  params: Promise<any>;
}) {
  const { subdomain } = await params;
  return (
    <html lang="en" translate="no">
      <body>
        <ThemeProvider tenant={subdomain}>
          <CartProvider>
            <>
              <Header />
              <Suspense fallback={<PageLoader />}>
                <Box
                  sx={{
                    marginY: 4,
                    minHeight: "60vh",
                    height: "100%",
                    position: "relative",
                  }}
                >
                  {children}
                  <Box sx={{ position: "fixed", right: 0, bottom: 0 }}>
                    <ChatBotComponent />
                  </Box>
                </Box>
              </Suspense>
              <Footer />
            </>
          </CartProvider>
        </ThemeProvider>
      </body>
    </html>
  );
}
